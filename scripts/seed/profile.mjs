/**
 * The Leader Profile's tests as rows, generated: data/profile/ and data/config/profile-bands.json in,
 * supabase/migrations/0012_profile_v1.sql out (CLAUDE.md, Model as data; handoff 9).
 *
 *   npm run seed:profile                    # validate the data and write 0012
 *   node scripts/seed/profile.mjs --check   # exit 1 when the committed 0012 differs; writes nothing
 *
 * The same rules as scripts/seed/model.mjs: validated first (lib/profile/schema.ts), deterministic (no clock
 * and no random id), and hashed (each test version stores the SHA-256 of the canonical JSON of its data
 * file). Version 1 renders the files named v1 and band set version 1. A later version is a new data file
 * and a new migration, never an edit of 0012 once applied (CLAUDE.md invariant 14).
 *
 * `render()` is pure, so tests/unit/profile.test.ts compares the committed file with it.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { bodyHash } from './model.mjs'

const ROOT = fileURLToPath(new URL('../../', import.meta.url))

export const OUTPUT = 'supabase/migrations/0012_profile_v1.sql'

export const FILES = {
  quick: 'data/profile/quick.v1.json',
  full: 'data/profile/full.v1.json',
  bands: 'data/config/profile-bands.json',
}

/** The data files as parsed JSON, not yet validated */
export function readFiles(root = ROOT) {
  return Object.fromEntries(Object.entries(FILES).map(([name, path]) => [name, JSON.parse(readFileSync(join(root, path), 'utf8'))]))
}

const str = (s) => `'${String(s).replace(/'/g, "''")}'`
const en = (text) => str(`{"en": ${JSON.stringify(text)}}`)
const values = (rows) => rows.map((r) => `  (${r.join(', ')})`).join(',\n')
const section = (title) => `-- ${'-'.repeat(64)} ${title}`
const testId = (t) => `(select t.id from app.profile_test t where t.key = ${str(t.key)} and t.version = ${t.version})`

const HEADER = `-- 0012_profile_v1.sql — version 1 of the Leader Profile's tests, as rows: the quick test (Mini-IPIP, 20 items,
-- five domains) and the full test (IPIP-NEO-120, 120 items, five domains and 30 facets), both public domain
-- and parsed from the sources handoff section 9 names, and band set version 1 (D-31).
--
-- GENERATED by scripts/seed/profile.mjs from data/profile/ and data/config/profile-bands.json. Do not edit
-- it by hand. \`node scripts/seed/profile.mjs --check\` fails when this file and the data disagree. Once
-- applied, a change is a new data file and a new migration, never an edit of this one (invariant 14).
--
-- Each test is inserted as a draft, given its traits and items, then published: the triggers of 0011
-- refuse a change to a published test. body_hash is the SHA-256 of the canonical JSON of its data file.`

/** The migration, as text. Pure: the same data gives the same bytes. */
export function render({ quick, full, bands }) {
  const out = [HEADER, '']
  const band = bands.find((b) => b.version === 1)
  out.push(section('band set, version 1 (D-31: equal thirds of the answer scale)'))
  out.push('insert into app.profile_band_set (version, lower_below, higher_above, valid_from) values')
  out.push(values([[band.version, band.lowerBelow.toFixed(2), band.higherAbove.toFixed(2), str(band.validFrom)]]) + ';', '')
  for (const t of [quick, full]) {
    out.push(section(`the ${t.key} test: ${t.name}, version ${t.version}`))
    out.push('insert into app.profile_test (key, version, name, citation, status, body_hash) values')
    out.push(values([[str(t.key), t.version, str(t.name), str(t.source.citation), str('draft'), str(bodyHash(t))]]) + ';', '')
    out.push('insert into app.profile_trait (test_id, key, kind, domain, name, ordinal)')
    out.push(`select ${testId(t)}, x.key, x.kind, x.domain, x.name::jsonb, x.ordinal`)
    out.push('from (values')
    out.push(
      values([
        ...t.domains.map((d) => [str(d.key), str('domain'), str(d.key), en(d.name), d.ordinal]),
        ...t.facets.map((f) => [str(f.key), str('facet'), str(f.domain), en(f.name), f.ordinal]),
      ]),
    )
    out.push(') as x (key, kind, domain, name, ordinal);', '')
    out.push('insert into app.profile_item (test_id, ordinal, text, trait, keyed)')
    out.push(`select ${testId(t)}, x.ordinal, x.text::jsonb, x.trait, x.keyed`)
    out.push('from (values')
    out.push(values(t.items.map((i) => [i.ordinal, en(i.text), str(i.trait), i.keyed])))
    out.push(') as x (ordinal, text, trait, keyed);', '')
  }
  out.push('-- published last: from here on their traits and items never change')
  out.push("update app.profile_test set status = 'published' where version = 1 and key in ('quick', 'full');")
  return out.join('\n') + '\n'
}

async function main(args) {
  const { tsImport } = await import('tsx/esm/api')
  const { profileTestSchema } = await tsImport('../../lib/profile/schema.ts', import.meta.url)
  const files = readFiles()
  for (const key of ['quick', 'full']) {
    const r = profileTestSchema.safeParse(files[key])
    if (!r.success) {
      console.error(`${FILES[key]}:\n${r.error.issues.map((i) => `  ${i.path.join('.')}: ${i.message}`).join('\n')}`)
      process.exit(1)
    }
  }
  const sql = render(files)
  const path = join(ROOT, OUTPUT)
  const counts = `quick ${files.quick.items.length} items, full ${files.full.items.length} items and ${files.full.facets.length} facets`
  if (args.includes('--check')) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== sql) {
      console.error(`${OUTPUT} differs from what the data generates. Before it is applied, run npm run seed:profile;`)
      console.error('after, a change is a new data version and a new migration (CLAUDE.md invariant 14).')
      process.exit(1)
    }
    console.log(`${OUTPUT} matches the data (${counts})`)
    return
  }
  writeFileSync(path, sql)
  console.log(`wrote ${OUTPUT} (${counts})`)
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) await main(process.argv.slice(2))
