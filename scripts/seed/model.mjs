/**
 * The model's rows, generated: data/ in, supabase/migrations/0004_model_v1.sql out (CLAUDE.md, Model as
 * data; REUSE 4.10).
 *
 *   npm run seed:model                    # validate data/ and write 0004
 *   node scripts/seed/model.mjs --check   # exit 1 when the committed 0004 differs; writes nothing
 *
 * 1. **Validated first.** lib/model/schema.ts checks every file, the copy rules included. A finding stops
 *    the run before anything is written.
 * 2. **Deterministic.** The same data gives the same bytes: no clock and no random id. The database makes
 *    every id, and a row finds another by its key or code.
 * 3. **Hashed.** An instrument version stores the SHA-256 of the canonical JSON it was made from: keys
 *    sorted at every depth, no whitespace. The scan's body is its file; the Full diagnostic's is the bank's
 *    version, scales and core items. The hash is made here, not in jsonb, which reorders keys (REUSE 4.10).
 * 4. **Version 1.** It renders the bank and scan files named v1, cut-off version 1 and price version 1.
 *    A later version is a new data file or row and a new migration, never an edit of 0004 (CLAUDE.md
 *    invariant 14).
 *
 * `render()` is pure, so tests/unit/model.test.ts compares the committed file with it.
 * Pattern origin: Orgpuls lib/modules/schema.ts (canonicalJson, bodyHash) @ 6f5d441.
 */
import { createHash } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const ROOT = fileURLToPath(new URL('../../', import.meta.url))

export const OUTPUT = 'supabase/migrations/0004_model_v1.sql'

export const FILES = {
  instruments: 'data/instrument/instruments.json',
  bank: 'data/instrument/bank.v1.json',
  scan: 'data/instrument/scan.v1.json',
  cutoffs: 'data/config/cutoffs.json',
  settings: 'data/config/settings.json',
  plans: 'data/config/plans.json',
}

/** The data files as parsed JSON, not yet validated */
export function readFiles(root = ROOT) {
  return Object.fromEntries(Object.entries(FILES).map(([name, path]) => [name, JSON.parse(readFileSync(join(root, path), 'utf8'))]))
}

/** JSON with keys sorted at every depth, so the same content always hashes the same */
export function canonicalJson(value) {
  const walk = (v) => {
    if (Array.isArray(v)) return v.map(walk)
    if (v && typeof v === 'object') return Object.fromEntries(Object.keys(v).sort().map((k) => [k, walk(v[k])]))
    return v
  }
  return JSON.stringify(walk(value))
}

export const bodyHash = (body) => createHash('sha256').update(canonicalJson(body)).digest('hex')

/** What each version is made from: the scan file; the bank's version, scales and core items */
export function versionBodies(model) {
  return {
    scan: model.scan,
    diagnostic: {
      version: model.bank.version,
      factors: model.bank.factors,
      items: model.bank.items.filter((item) => item.use === 'core'),
    },
  }
}

// ---------------------------------------------------------------- SQL
const str = (s) => `'${String(s).replace(/'/g, "''")}'`
const en = (text) => str(`{"en": ${JSON.stringify(text)}}`)
const lit = (v) => (v === null ? 'null' : typeof v === 'string' ? str(v) : String(v))
const values = (rows) => rows.map((r) => `  (${r.join(', ')})`).join(',\n')
const section = (title) => `-- ${'-'.repeat(64)} ${title}`
const versionId = (instrument) =>
  `(select v.id from app.instrument_version v join app.instrument i on i.id = v.instrument_id where i.key = ${str(instrument)} and v.version = 1)`
const itemId = '(select it.id from app.item it where it.code = x.code and it.revision = 1)'

const HEADER = `-- 0004_model_v1.sql — version 1 of the model, as rows: 21 scales and 3 outcomes, the 96 items of the
-- bank, the Leadership Team Scan and the Full diagnostic, cut-offs, settings and plans (handoff 9).
--
-- GENERATED by scripts/seed/model.mjs from data/. Do not edit it by hand.
-- \`node scripts/seed/model.mjs --check\` fails when this file and data/ disagree. Until this migration is
-- applied, change the data and run \`npm run seed:model\`. Once applied, a reworded item or a later bank is
-- a new data file and a new migration, never an edit of this one (CLAUDE.md invariant 14).
--
-- 1. Ids are the database's own; a row refers to another by key or code, never by a hard-coded id.
-- 2. Each instrument version is inserted as a draft, given its items, then published: the trigger of 0003
--    refuses an item added to a published version.
-- 3. body_hash is the SHA-256 of the canonical JSON the version was made from (scripts/seed/model.mjs).
-- 4. Candidate items are stored with use = 'candidate' and are in no version (handoff 9).`

/** The migration, as text. Pure: the same model gives the same bytes. */
export function render(model) {
  const { instruments, bank, scan, settings, plans } = model
  const cutoffs = model.cutoffs.filter((c) => c.version === 1)
  const hashes = Object.fromEntries(Object.entries(versionBodies(model)).map(([k, body]) => [k, bodyHash(body)]))
  const core = bank.items.filter((item) => item.use === 'core')
  const prices = plans.flatMap((p) => p.prices.filter((x) => x.version === 1).map((x) => ({ plan: p.key, ...x })))
  const out = [HEADER, '']

  out.push(section('scales (Appendix A)'))
  out.push('insert into app.factor (key, name, layer, reading_type, evidence, ordinal) values')
  out.push(values(bank.factors.map((f) => [str(f.key), en(f.name), str(f.layer), str(f.readingType), lit(f.evidence), f.ordinal])) + ';', '')

  out.push(section('instruments (handoff 10 names)'))
  out.push('insert into app.instrument (key, name) values')
  out.push(values(instruments.map((i) => [str(i.key), en(i.name)])) + ';', '')

  out.push(section('scan themes (Appendix C)'))
  out.push('insert into app.scan_theme (key, name, ordinal) values')
  out.push(values(scan.themes.map((t) => [str(t.key), en(t.name), t.ordinal])) + ';', '')

  out.push(section(`items, bank version ${bank.version} (Appendix B)`))
  out.push('insert into app.item (code, revision, factor_id, text, use)')
  out.push('select x.code, 1, (select f.id from app.factor f where f.key = x.factor), x.text::jsonb, x.use')
  out.push('from (values')
  out.push(values(bank.items.map((item) => [str(item.code), str(item.factor), en(item.text), str(item.use)])))
  out.push(') as x (code, factor, text, use);', '')

  out.push(section('instrument versions, drafts until their items are in'))
  out.push('insert into app.instrument_version (instrument_id, version, status, body_hash)')
  out.push("select (select i.id from app.instrument i where i.key = x.instrument), x.version, 'draft', x.body_hash")
  out.push('from (values')
  out.push(values([[str('scan'), scan.version, str(hashes.scan)], [str('diagnostic'), bank.version, str(hashes.diagnostic)]]))
  out.push(') as x (instrument, version, body_hash);', '')

  out.push(`-- the Leadership Team Scan, version ${scan.version}: twelve core items in Appendix C order, each with its theme`)
  out.push('insert into app.instrument_version_item (instrument_version_id, item_id, ordinal, theme_id)')
  out.push(`select ${versionId('scan')},`)
  out.push(`       ${itemId},`)
  out.push('       x.ordinal,')
  out.push('       (select t.id from app.scan_theme t where t.key = x.theme)')
  out.push('from (values')
  out.push(values(scan.items.map((s) => [s.order, str(s.code), str(s.theme)])))
  out.push(') as x (ordinal, code, theme);', '')

  out.push(`-- the Full diagnostic, version ${bank.version}: the ${core.length} core items in bank order; no candidate`)
  out.push('insert into app.instrument_version_item (instrument_version_id, item_id, ordinal)')
  out.push(`select ${versionId('diagnostic')},`)
  out.push(`       ${itemId},`)
  out.push('       x.ordinal')
  out.push('from (values')
  out.push(values(core.map((item, i) => [i + 1, str(item.code)])))
  out.push(') as x (ordinal, code);', '')

  out.push('-- published last: from here on their item lists never change')
  out.push("update app.instrument_version v set status = 'published'")
  out.push('from app.instrument i')
  out.push("where i.id = v.instrument_id and v.version = 1 and i.key in ('scan', 'diagnostic');", '')

  out.push(section('cut-offs, version 1 (handoff 7; owner C6)'))
  out.push('insert into app.cutoff_set (version, agreement_high, agreement_low, higher_priority_below, higher_strength_from,')
  out.push('  lower_priority_from, lower_strength_below, change_margin, valid_from) values')
  out.push(
    values(
      cutoffs.map((c) => [
        c.version,
        c.agreementHigh.toFixed(2),
        c.agreementLow.toFixed(2),
        c.higherPriorityBelow.toFixed(1),
        c.higherStrengthFrom.toFixed(1),
        c.lowerPriorityFrom.toFixed(1),
        c.lowerStrengthBelow.toFixed(1),
        c.changeMargin.toFixed(1),
        str(c.validFrom),
      ]),
    ) + ';',
    '',
  )

  out.push(section('settings (handoff 8, Configuration)'))
  out.push('insert into app.setting (key, scope, default_value, min_value, max_value, fixed, unit) values')
  out.push(values(settings.map((s) => [str(s.key), str(s.scope), str(JSON.stringify(s.default)), lit(s.min), lit(s.max), s.fixed, str(s.unit)])) + ';', '')

  out.push(section('plans (handoff 1: test prices)'))
  out.push('insert into app.plan (key, name, max_groups, max_members, ordinal) values')
  out.push(values(plans.map((p) => [str(p.key), en(p.name), lit(p.maxGroups), p.maxMembers, p.ordinal])) + ';', '')
  out.push('insert into app.plan_feature (plan_key, feature) values')
  out.push(values(plans.flatMap((p) => p.features.map((f) => [str(p.key), str(f)]))) + ';')
  if (prices.length) {
    out.push('')
    out.push('-- minor units: 180000 is $1,800.00')
    out.push('insert into app.plan_price (plan_key, interval, currency, amount_minor, version, valid_from) values')
    out.push(values(prices.map((x) => [str(x.plan), str(x.interval), str(x.currency), x.amountMinor, x.version, str(x.validFrom)])) + ';')
  }
  return out.join('\n') + '\n'
}

// ---------------------------------------------------------------- run as a script
async function main(args) {
  const { tsImport } = await import('tsx/esm/api')
  const { parseModel } = await tsImport('../../lib/model/schema.ts', import.meta.url)
  let model
  try {
    model = parseModel(readFiles())
  } catch (error) {
    console.error(error.message)
    process.exit(1)
  }
  const sql = render(model)
  const path = join(ROOT, OUTPUT)
  const outcomes = model.bank.factors.filter((f) => f.layer === 'outcomes').length
  const counts = `${model.bank.factors.length - outcomes} scales and ${outcomes} outcomes, ${model.bank.items.length} items, ${model.scan.items.length} scan items`
  if (args.includes('--check')) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== sql) {
      console.error(`${OUTPUT} differs from what data/ generates. Before it is applied, run npm run seed:model;`)
      console.error('after, a change is a new data version and a new migration (CLAUDE.md invariant 14).')
      process.exit(1)
    }
    console.log(`${OUTPUT} matches data/ (${counts})`)
    return
  }
  writeFileSync(path, sql)
  console.log(`wrote ${OUTPUT} (${counts})`)
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) await main(process.argv.slice(2))
