/**
 * Writes supabase/functions/_shared/messages.gen.ts from messages/en.json and lib/brand.ts (D-53).
 *
 *   node scripts/functions/build.mjs           write it
 *   node scripts/functions/build.mjs --check   exit 1 when the committed file differs (tests/unit/mail.test.ts asks too)
 *
 * The mail texts live in messages/en.json under `mail`, like every other string, so `npm run verify:i18n`
 * holds them to the copy rules. An edge function cannot read that file at run time, so this copies the `mail`
 * subtree and the product's name into the function's own folder. The file is committed, so what is deployed
 * (through the Supabase MCP's deploy_edge_function, on the LeaderPact project only) is what was reviewed.
 */
import { readFileSync, writeFileSync } from 'node:fs'

const OUT = 'supabase/functions/_shared/messages.gen.ts'
const mail = JSON.parse(readFileSync('messages/en.json', 'utf8')).mail
const brand = readFileSync('lib/brand.ts', 'utf8').match(/export const PRODUCT_NAME = '([^']+)'/)
if (!mail || !brand) {
  console.error('messages/en.json has no mail messages, or lib/brand.ts no PRODUCT_NAME')
  process.exit(2)
}
const text =
  `// generated by scripts/functions/build.mjs from messages/en.json and lib/brand.ts: do not edit\n` +
  `export const PRODUCT_NAME = ${JSON.stringify(brand[1])}\n` +
  `export const MAIL: Record<string, string> = ${JSON.stringify(mail, null, 2)}\n`

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(OUT, 'utf8')
  } catch {}
  if (current !== text) {
    console.error(`${OUT} is out of date: run node scripts/functions/build.mjs`)
    process.exit(1)
  }
  console.log(`${OUT} is up to date`)
} else {
  writeFileSync(OUT, text)
  console.log(`wrote ${OUT}`)
}
